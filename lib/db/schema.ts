import { sql } from "drizzle-orm";
import { boolean, check, index, integer, jsonb, pgTable, primaryKey, real, text, timestamp, uniqueIndex } from "drizzle-orm/pg-core";

// ── Auth (tables and columns as Better Auth expects them) ──────────────────

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at").notNull().defaultNow(),
  // When the reader asked for the newsletter (NEWSLETTER=true servers); null =
  // not subscribed. Kept as a time, so the operator can show when they agreed.
  newsletterConsentAt: timestamp("newsletter_consent_at"),
  // When the account last signed in or used Bookplate, to the day (see
  // markSeen in lib/auth.ts) — for finding long-unused accounts.
  lastSeenAt: timestamp("last_seen_at").notNull().defaultNow(),
  // Info boxes the reader chose not to see again (ids from lib/hints.ts).
  dismissedHints: text("dismissed_hints").array().notNull().default(sql`'{}'::text[]`),
  // Optional features the reader has switched on (ids from lib/features.ts).
  features: text("features").array().notNull().default(sql`'{}'::text[]`),
});

export const session = pgTable(
  "session",
  {
    id: text("id").primaryKey(),
    expiresAt: timestamp("expires_at").notNull(),
    token: text("token").notNull().unique(),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
  },
  (t) => [index("session_user_idx").on(t.userId)]
);

export const account = pgTable(
  "account",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at"),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at"),
    scope: text("scope"),
    password: text("password"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [index("account_user_idx").on(t.userId)]
);

export const verification = pgTable("verification", {
  id: text("id").primaryKey(),
  identifier: text("identifier").notNull(),
  value: text("value").notNull(),
  expiresAt: timestamp("expires_at").notNull(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at").notNull().defaultNow(),
});

// Failed-password counting per account (see lib/authThrottle.ts).
export const authThrottle = pgTable("auth_throttle", {
  key: text("key").primaryKey(), // e.g. "sign-in:reader@example.com"
  failures: integer("failures").notNull(),
  windowStart: timestamp("window_start").notNull(),
});

// ── Library ────────────────────────────────────────────────────────────────
// Every row belongs to a user. Ids are generated by the client (UUIDs, or
// older "seed-…" ids from imported libraries), so they are only unique per
// user: two accounts importing the same export must not collide.

export const book = pgTable(
  "book",
  {
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    id: text("id").notNull(),
    title: text("title").notNull(),
    author: text("author").notNull(),
    isbn: text("isbn"), // ISBN-13 or ISBN-10, digits only (plus a trailing X)
    olWorkId: text("ol_work_id"), // Open Library work, e.g. OL893415W (books added from the catalogue)
    genre: text("genre"),
    pages: integer("pages"),
    format: text("format"),
    status: text("status").notNull(),
    copy: boolean("copy"),
    rating: real("rating").notNull().default(0),
    dateRead: text("date_read"), // ISO yyyy-mm-dd, kept as text like the app uses it
    pastReads: jsonb("past_reads").$type<{ date?: string }[]>(), // earlier finishes, oldest first; null = none
    shortNotes: text("short_notes"), // legacy one-line notes from before notes pages
    coverImage: text("cover_image"),
    colorIndex: integer("color_index").notNull().default(0),
    addedAt: text("added_at").notNull(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.id] })]
);

export const note = pgTable(
  "note",
  {
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    bookId: text("book_id").notNull(),
    markdown: text("markdown").notNull(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.bookId] })]
);

// Reading progress: one entry per book per day (a second update on the same
// day replaces it). The percentage is always stored; the page too when the
// book has a page count. The first entry marks when the book was started.
export const readingProgress = pgTable(
  "reading_progress",
  {
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    bookId: text("book_id").notNull(),
    date: text("date").notNull(), // ISO yyyy-mm-dd, the reader's local date
    page: integer("page"),
    percent: real("percent").notNull(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.bookId, t.date] })]
);

export const vocabEntry = pgTable(
  "vocab_entry",
  {
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    id: text("id").notNull(),
    word: text("word").notNull(),
    phonetic: text("phonetic"),
    partOfSpeech: text("part_of_speech"),
    definition: text("definition").notNull(),
    example: text("example"),
    synonyms: text("synonyms").array(),
    bookId: text("book_id"),
    addedAt: text("added_at").notNull(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.id] })]
);

// A public page of one year's reading (lib/showcase.ts), at /s/<id>. One per
// reader. It holds only the reader's choices; the books are read live each
// time it's opened. The id is the whole address, so it's long and random, and
// never logged.
export const showcase = pgTable(
  "showcase",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    year: integer("year").notNull(),
    name: text("name"), // shown on the page; null = no name
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [uniqueIndex("showcase_user_idx").on(t.userId)]
);

// ── Social (SOCIAL=true servers; lib/social/) ─────────────────────────────
// Empty on servers without it. Every row belongs to the readers it names and
// goes with their accounts.

// A reader's public face: the handle others find them by and what they let
// others see. No row = no profile, and nobody else can see anything.
export const profile = pgTable(
  "profile",
  {
    userId: text("user_id")
      .primaryKey()
      .references(() => user.id, { onDelete: "cascade" }),
    handle: text("handle").notNull(), // lower case, [a-z0-9_]{3,24}
    bio: text("bio"),
    visibility: text("visibility").notNull().default("friends"), // private | friends | public
    shareReading: boolean("share_reading").notNull().default(true), // what's being read now
    shareRatings: boolean("share_ratings").notNull().default(true),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [uniqueIndex("profile_handle_idx").on(t.handle)]
);

// Two readers who are friends, stored once per pair with the smaller id
// first, so "are they friends?" is one lookup.
export const friendship = pgTable(
  "friendship",
  {
    userA: text("user_a")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    userB: text("user_b")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.userA, t.userB] }),
    index("friendship_user_b_idx").on(t.userB),
    check("friendship_order", sql`${t.userA} < ${t.userB}`),
  ]
);

// A request waiting for an answer. Answering removes it either way.
export const friendRequest = pgTable(
  "friend_request",
  {
    fromUser: text("from_user")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    toUser: text("to_user")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.fromUser, t.toUser] }),
    index("friend_request_to_idx").on(t.toUser),
    check("friend_request_not_self", sql`${t.fromUser} <> ${t.toUser}`),
  ]
);

// An invite link, /f/<token>: whoever opens it can ask to be the reader's
// friend. Like a showcase id, the token is the whole key and never logged.
export const friendInvite = pgTable(
  "friend_invite",
  {
    token: text("token").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    expiresAt: timestamp("expires_at").notNull(),
    usesLeft: integer("uses_left"), // null = any number until it expires
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (t) => [index("friend_invite_user_idx").on(t.userId)]
);

// A reader the blocker never wants to hear from: each is hidden from the other.
export const block = pgTable(
  "block",
  {
    blocker: text("blocker")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    blocked: text("blocked")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.blocker, t.blocked] }),
    index("block_blocked_idx").on(t.blocked),
    check("block_not_self", sql`${t.blocker} <> ${t.blocked}`),
  ]
);

// A book one friend suggests to another. Not in the recipient's library
// until they add it (then added_book_id says which book it became).
export const recommendation = pgTable(
  "recommendation",
  {
    id: text("id").primaryKey(),
    fromUser: text("from_user")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    toUser: text("to_user")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    author: text("author").notNull(),
    isbn: text("isbn"),
    olWorkId: text("ol_work_id"),
    workKey: text("work_key").notNull(), // lib/social/workKey.ts
    note: text("note"),
    state: text("state").notNull().default("new"), // new | seen | added | dismissed
    addedBookId: text("added_book_id"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (t) => [index("recommendation_to_idx").on(t.toUser, t.createdAt), index("recommendation_from_idx").on(t.fromUser)]
);

// Something for a reader to see: a friend request, a recommendation… `kind`
// says what, `objectRef` points at it (its meaning depends on the kind).
export const notification = pgTable(
  "notification",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    kind: text("kind").notNull(),
    actorId: text("actor_id").references(() => user.id, { onDelete: "cascade" }),
    objectRef: text("object_ref"),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    readAt: timestamp("read_at"),
  },
  (t) => [index("notification_user_idx").on(t.userId, t.createdAt)]
);
